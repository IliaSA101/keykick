/**
 * Масштаб экрана от окна (docs/design.md, 04.11, «крупный экран»): вёрстка выверена на окне
 * 1024×640, на больших окнах она растёт целиком, одним множителем, — пропорции те же.
 * Размеры окна приходят снаружи: движок окна не видит.
 */

/** Эталонное окно: на нём масштаб 1 и всё как выверено. */
export const BASE_W = 1024;
export const BASE_H = 640;
/** Потолок: на огромном мониторе буквы не становятся плакатными. */
export const MAX_SCALE = 2;

/**
 * Масштаб для окна w×h: min(w/1024, h/640), не меньше 1 (окно меньше эталона — как было,
 * со своими правилами узких окон) и не больше потолка. Сотые — чтобы мелкие сдвиги окна не
 * перекладывали вёрстку.
 */
export function uiScale(w: number, h: number): number {
  const s = Math.min(w / BASE_W, h / BASE_H);
  return Math.floor(Math.min(MAX_SCALE, Math.max(1, s)) * 100) / 100;
}

/**
 * Две шкалы (docs/specs/006-page-scale.md): матч — сцена, растёт с окном множителем uiScale;
 * страницы и верхняя панель — вдвое медленнее, с потолком: на большом экране, который стоит
 * дальше от глаз, буква страницы остаётся у детской нормы, а не плакатной.
 */
export const PAGE_GROWTH = 0.5;
export const PAGE_MAX = 1.5;

/**
 * Множитель страниц для множителя матча s: 1 + (s − 1) · 0,5 в целых сотых вниз, не больше потолка.
 * Считаем в целых сотых: формула в дробях из-за двоичного округления на 1,14 даёт 1,06, а не 1,07.
 */
export function pageScale(s: number): number {
  const grown = Math.floor((Math.round(s * 100) - 100) * PAGE_GROWTH);
  return Math.min(PAGE_MAX * 100, 100 + Math.max(0, grown)) / 100;
}

/**
 * Ширина экрана матча в px эталона, начиная с которой по бокам поля есть место для форм:
 * колонка матча (клавиатура 760 + 60) и по колонке ~100 с отступами с каждой стороны.
 */
export const SIDE_KITS_FROM = 1056;

/** Есть ли по бокам поля место для крупных форм; width — ширина окна в px эталона (окно / масштаб). */
export function hasSideRoom(width: number): boolean {
  return width >= SIDE_KITS_FROM;
}
