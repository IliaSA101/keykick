/**
 * Витрина матча (спека 017-Т8, 019-Р33): адрес с `at` — быстрая проверка фазы, а не игра. Единое правило для всех, кто
 * на это смотрит: страница матча (хранилище в памяти, в сохранение ничего не пишет), каркас приложения (время игры не
 * идёт), охрана входа (в выпуске такой адрес уводит на карту). Любое значение `at`, в том числе незнакомое, — витрина.
 */
export function hasAt(query: Readonly<Record<string, unknown>>): boolean {
  const v = query.at;
  return (Array.isArray(v) ? (v as unknown[])[0] : v) !== undefined;
}
